KWERENDY:

Wszyscy klienci co mają zamówienie:

SELECT IMIE, NAZWISKO, EMAIL 
FROM KLIENCI 
WHERE CZY_MA_ZAMOWINIE = TRUE;

Lista producentów z Polski lub którzy mają aktywny koncern:

SELECT * FROM PRODUCENT 
WHERE KRAJ = 'Polska' OR CZY_AKTYWNA = TRUE;

Wszystkie silniki z więcej niż 4 tłoków:
SELECT NAZWA, IL_TLOK FROM SILNIK WHERE IL_TLOK > 4;

Wyświetlenie zamówień:

SELECT ID_ZAMOWIENIA, DATA_ZLOZENIA_ZAMOWIENIA FROM ZAMOWIENIA;

Samochody z manualną skrzynią biegów:

SELECT MARKA, MODEL FROM SAMOCHOD WHERE SKRZYNIA_BIEGOW = 'Manualna';

Klienci z Warszawy:

SELECT IMIE, NAZWISKO FROM KLIENCI WHERE MIASTO = 'Warszawa';



