TWORZENIE TABEL:

CREATE TABLE PRODUCENT(
ID_PROD BIGINT,
NAZWA VARCHAR(50),
KRAJ VARCHAR(50),
MIASTO VARCHAR(150),
KONCERN VARCHAR(50),
CZY_AKTYWNA BOOLEAN
);

CREATE TABLE SAMOCHOD(
ID_SAMOCHODU BIGINT,
MARKA VARCHAR(50),
MODEL VARCHAR(50),
GENERECJA VARCHAR(50),
SKRZYNIA_BIEGOW VARCHAR(30),
PALIWO VARCHAR(20),
ID_SILNIK BIGINT,
ID_WYPOSAZENIE BIGINT,
ID_OPON
CZY_MA_UBEZPIECZENIE BOOLEAN
);

CREATE TABLE SILNIK(
ID_SILNIK BIGINT,
NAZWA TEXT,
ROCZNIK INT,
IL_TLOK SMALLINT,
CZY_WOLNOSACY BOOLEAN,
OBJETOSC_CM3 INT,
IL_KM INT,
MOC INT
);

CREATE TABLE WYPOSAZENIE(
ID_WYPOSAZENIE BIGINT,
TAPICERKA VARCHAR(10),
KLIMATYZACJA BOOLEAN,
TEMPOMAT BOOLEAN,
OGRZEWANIE_POSTOJOWE BOOLEAN,
NAWIGACJA BOOLEAN,
SYSTEM_AUDIO BOOLEAN,
GRZANE_FOTELE BOOLEAN,
REGULOWANE_SIEDZENIA BOOLEAN,
CZUJNIK_DESZCZU BOOLEAN,
SWIATLA_KSENONOWE BOOLEAN
);

CREATE TABLE OPONY(
ID_OPONY BIGINT,
TYP_OPONY VARCHAR(30),
SZEROKOSC INT,
KONSTRUKCJA VARCHAR(5)
PROFIL INT,
SREDNICA_FELGI FLOAT,
WSKAZNIK_PREDKOSCI VARCHAR(5)
);

CREATE TABLE KLIENCI(
ID_KLIENTA BIGINT,
IMIE TEXT,
NAZWISKO TEXT,
KRAJ VARCHAR(100),
MIASTO VARCHAR(100),
ULICA TEXT,
EMAIL TEXT,
TEL_NUMER TEXT,
CZY_MA_ZAMOWINIE BOOLEAN,
ID_ZAMOWIENIA BIGINT
);

CREATE TABLE ZAMOWIENIA(
ID_ZAMOWIENIA BIGINT,
ID_KLIENTA BIGINT,
ID_SAMOCHODU BIGINT,
DATA_ZLOZENIA_ZAMOWIENIA DATETIME,
DOD_INFORMACJE TEXT
);



